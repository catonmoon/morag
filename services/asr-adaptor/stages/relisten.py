"""Переслушивание подозрительных кусков: модель ошиблась — послушаем это место ещё раз.

ASR на невнятном звуке не молчит, а **зацикливается**: вместо речи выдаёт серию одной буквы, ряд
знаков, повтор слова. Речь, которая там звучала, теряется молча — и до сих пор терялась навсегда,
потому что дальше по конвейеру никто не спрашивает «а это вообще похоже на речь?».

**Что делает стадия.** Смотрит на выход пасса-2 и на времена его сегментов, находит подозрительные
куски и **слушает их ещё раз — чистым ухом**: то же окно, но БЕЗ подсказки и с запасом по краям.
Дальше решает по услышанному:

    петля → в чистом ухе речь      → берём речь (то, ради чего всё затевается);
    петля → в чистом ухе пусто     → честная дыра: речи там нет, и сочинять нечего;
    петля → петля и в чистом ухе   → оставляем как было и говорим об этом вслух.

⚠️⚠️ **Чистое ухо — не украшение, а правило.** Подсказка пасса-2 несёт канонические написания, и
модель на невнятном звуке охотно «слышит» подсказанное: так в расшифровку попадают слова, которых
в звуке нет. Переслушивание без подсказки — единственный способ узнать, что там на самом деле.

⚠️ **Замерено (18 мест в четырёх записях, 2026-09):** одно только переслушивание чистым ухом вернуло
197 слов живой речи; из 18 мест 10 стали речью, 5 — честной тишиной. Отступ по температуре при
этом ВРЕДЕН в полном виде (лесенка до 1.0 сочиняет текст на чужих языках — 3 случая из 18), а в
мягком (до 0.4) безопасен и снимает остаток. Поэтому порядок такой: сперва чистое ухо при
temperature 0, и только если порча осталась — мягкий отступ.

⚠️ Стадия НЕ имеет права уронить запись: любое исключение здесь стоит одного куска, а не часа
работы. Тот же принцип, что у пасса-2.
"""

from __future__ import annotations

import re

# --- что считаем подозрительным ----------------------------------------------------------------
#
# Пороги измерены на живом корпусе (193 записи, 1.44 млн слов), а не назначены: у каждой формы
# в распределении есть разрыв между живой речью и петлёй, и порог поставлен в него.

CHAR_RUN = 8        # «ИИИИИИИИ» — серия одного символа внутри слова (3 — это «ааа» в речи)
PUNCT_RUN = 5       # «!!!!!» — ряд знаков (три — это многоточие)
TOKEN_REPEAT = 3    # «СловоСловоСлово» — повтор подстроки внутри одного токена
WORD_RUN = 8        # слово подряд восемь раз — в живой речи не встречается
STRETCH_SEC = 5.0   # сегмент в пять секунд на одно-два слова — здесь потеряна речь
STRETCH_WORDS = 2
# Плотность речи. Замерено на 19 978 репликах живого корпуса: медиана 2.0 слова в секунду, 5-й
# процентиль 0.97, 1-й — 0.40. Ниже 0.5 живой речи практически не бывает, а то, что там есть, —
# ровно наша порча: «Полюбим.» на 41 секунду, «СловоСловоСлово», серия одной буквы. Порог стоит в
# этом разрыве, а короткие куски не трогаем вовсе: на пяти секундах пауза легко даёт 0.4.

_CHAR = re.compile(rf"([^\W\d_])\1{{{CHAR_RUN - 1},}}", re.U)
_PUNCT = re.compile(rf"([!?.,…])\1{{{PUNCT_RUN - 1},}}")
_TOKEN = re.compile(rf"\b([^\W\d_]{{2,15}}?)\1{{{TOKEN_REPEAT - 1},}}\b", re.U)
_WORD = re.compile(r"[^\W\d_]+", re.U)

SPARSE_RATE = 0.5   # слов в секунду, ниже которого кусок считается потерявшим речь
SPARSE_SEC = 8.0    # и только для кусков длиннее этого

PAD_S = 1.5         # запас по краям окна: модели нужен разбег, чтобы попасть в речь
MILD = '0,0.2,0.4'  # мягкий отступ — второй заход, если чистое ухо тоже сорвалось


def looped(text: str) -> str:
    """Какая петля видна в тексте — или пусто, если текст здоров."""
    if _CHAR.search(text or ''):
        return 'char'
    if _PUNCT.search(text or ''):
        return 'punct'
    for m in _TOKEN.finditer(text or ''):
        if len(set(m.group(1))) > 1:        # «ИИИИ» это серия символа, её ловит первая проверка
            return 'token'
    words = [w.lower() for w in _WORD.findall(text or '')]
    run = 1
    for a, b in zip(words, words[1:]):
        run = run + 1 if a == b else 1
        if run >= WORD_RUN:
            return 'word'
    return ''


def stretched(segments) -> str:
    """Сегмент, растянутый во времени: пять секунд звука на одно слово — это не речь, а дыра."""
    for s in segments or ():
        try:
            sec = float(s.get('end') or 0) - float(s.get('start') or 0)
        except (TypeError, ValueError):
            continue
        if sec >= STRETCH_SEC and len(_WORD.findall(s.get('text') or '')) <= STRETCH_WORDS:
            return 'stretch'
    return ''


def sparse(chunk) -> str:
    """Кусок, в котором почти нет слов: двадцать секунд звука на три слова — речь потеряна.

    ⚠️ Эта проверка ловит то, чего не видят остальные: петля не всегда выглядит петлёй. В живом
    прогоне место с петлёй вышло как «И Извание И Извание» на тридцати секундах — ни серии
    символов, ни повтора восемь раз, а речи там нет.
    """
    try:
        sec = float(chunk.get('end') or 0) - float(chunk.get('start') or 0)
    except (TypeError, ValueError):
        return ''
    if sec < SPARSE_SEC:
        return ''
    return 'sparse' if len(_WORD.findall(chunk.get('raw') or '')) / sec < SPARSE_RATE else ''


def suspect(chunk) -> str:
    """Форма подозрения для куска пасса-2 — или пусто, если с ним всё хорошо."""
    return looped(chunk.get('raw') or '') or stretched(chunk.get('segments')) or sparse(chunk)


def verdict(was: str, now: str) -> str:
    """Что делать с местом, глядя на то, что услышало чистое ухо.

    ⚠️ Петлю меняем даже на ОДНО слово: замерено живьём — там, где в записи стояло «ИИИИИИИИИИИИИ»,
    в звуке одно «и». Одно верное слово честнее тринадцати выдуманных, поэтому у такого исхода
    своё имя («коротко»), а не «без изменений».
    """
    if looped(now):
        return 'петля осталась'
    if not now.strip():
        return 'тишина'
    n_now, n_was = len(_WORD.findall(now)), len(_WORD.findall(was))
    if n_now >= 3:
        return 'речь'
    # Одно-два слова — это «коротко», а не «речь»: разница важна, когда потом смотришь журнал и
    # решаешь, стоило ли вмешиваться. Меняем всё равно — одно верное слово честнее петли.
    return 'коротко' if n_now > n_was or looped(was) else 'без изменений'


def apply(chunk, text: str, segments, offset: float, decision: str) -> None:
    """Положить услышанное в кусок. Времена сегментов — АБСОЛЮТНЫЕ, как у пасса-2."""
    if decision == 'тишина':
        chunk['raw'], chunk['segments'] = '', []
        return
    if decision not in ('речь', 'коротко'):
        return
    chunk['raw'] = text
    chunk['segments'] = [{'start': round(offset + float(s.get('start') or 0.0), 2),
                          'end': round(offset + float(s.get('end') or 0.0), 2),
                          'text': (s.get('text') or '').strip()} for s in segments or ()]
    chunk['relistened'] = True
