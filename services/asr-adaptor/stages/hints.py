_SCHEMA = {
    'type': 'object',
    'properties': {'found': {'type': 'array', 'items': {
        'type': 'object',
        'properties': {'term': {'type': 'string'}, 'heard': {'type': 'string'}},
        'required': ['term', 'heard']}}},
    'required': ['found'],
}

# Тот же потолок, что у свободного прохода: деген-петля (одно слово сорок раз подряд) ловилась и
# здесь, а тесный кап рвёт JSON у честного батча.
_MAX_TOKENS = 8000

# Транслитерация для сравнения написаний ЧЕРЕЗ алфавиты: гарбл и каноник сплошь и рядом в разных
# письменностях («Kavka» → «Кафка», «Redisом» → «Редисом»), посимвольное сравнение дало бы им
# ноль. Три пары в конце — где латиница и кириллица звучат одинаково, а пишутся врозь.
_TRANSLIT = {'а': 'a', 'б': 'b', 'в': 'v', 'г': 'g', 'д': 'd', 'е': 'e', 'ё': 'e', 'ж': 'zh',
             'з': 'z', 'и': 'i', 'й': 'y', 'к': 'k', 'л': 'l', 'м': 'm', 'н': 'n', 'о': 'o',
             'п': 'p', 'р': 'r', 'с': 's', 'т': 't', 'у': 'u', 'ф': 'f', 'х': 'h', 'ц': 'c',
             'ч': 'ch', 'ш': 'sh', 'щ': 'sch', 'ъ': '', 'ы': 'y', 'ь': '', 'э': 'e', 'ю': 'yu',
             'я': 'ya'}

# Порог похожести гарбла и каноника. ⚠️ Не догадка: замерено на всех 43 подтверждённых правках
# закрытого корпуса рабочих встреч — минимум 0.57, медиана 0.86. Выдуманные привязки из
# прогонов гейта лежат заметно ниже: «Ковалёва» → «Кузнецова» 0.47, `SMTP` → «Редис» 0.22,
# `XY` → «Ковалёв» 0.20. Порог сохраняет ВСЕ известные пары и режет весь этот класс целиком.
# Это несущее правило: подсказка whisper — единственное место конвейера без последующей проверки.
SIM_MIN = 0.55


def _norm(s: str) -> str:
    return re.sub(r'[^0-9a-zа-яё]', '', s.lower())


def _key(s: str) -> str:
    """Написание, приведённое к одной письменности."""
    out = ''.join(_TRANSLIT.get(c, c) for c in _norm(s))
    return out.replace('ph', 'f').replace('x', 'ks').replace('c', 'k')


def similar(heard: str, term: str) -> float:
    return difflib.SequenceMatcher(None, _key(heard), _key(term)).ratio()


def _validate(found: list, batch: str, allowed: dict[str, str], log) -> list[dict]:
    """Пять правил отсева. Без них канал небезопасен: подсказка пасса-2 ничем не проверяется дальше.

    1. `term` не из предложенного списка — модель регулярно переписывает в него написание ИЗ
       ЧЕРНОВИКА («Редис» → `Redis`), то есть отменяет ту самую правку, ради которой всё затеяно;
    2. `heard` не встречается в этом батче — главный режим отказа «перечислила список с выдуманными
       гарблами»;
    3. `heard` == `term` — записано верно, подсказку не заслужило (бюджет 200 токенов);
    4. написания не похожи — ловит выдуманные привязки, в том числе фамилию к чужому месту;
    5. гейт редкости `_keep_one` — тот же, что у свободного прохода, против переводов.
    """
    out, drops = [], {}
    bnorm = _norm(batch)
    for f in found if isinstance(found, list) else []:
        if not isinstance(f, dict):
            continue
        term, heard = str(f.get('term') or '').strip(), str(f.get('heard') or '').strip()
        canon = allowed.get(_norm(term))
        if not term or not heard or canon is None:
            reason = 'не из списка'
        elif _norm(heard) not in bnorm:
            reason = 'нет в черновике'
        elif _norm(heard) == _norm(canon):
            reason = 'записано верно'
        elif similar(heard, canon) < SIM_MIN:
            reason = 'не похоже'
        elif not _keep_one(heard, canon):
            reason = 'гейт редкости'
        else:
            out.append({'heard': heard, 'canonicals': [canon]})
            continue
        drops[reason] = drops.get(reason, 0) + 1
    if drops:
        log.info('hints: отсеяно %s', ', '.join(f'{k} {v}' for k, v in sorted(drops.items())))
    return out


async def _one_batch(llm, batch: str, terms: list[str], names: list[str], about: str,
                     allowed: dict[str, str], tag: str) -> list[dict]:
    """Один батч черновика.

    ⚠️ Ошибка вызова → ПУСТОЙ список, а не `None`: у свободного прохода `None` означает «сорвалось»
    и питает предохранитель «все вызовы мертвы, роняем джобу». Seed в этот счёт входить не должен —
    без него запись выйдет ровно такой, какой выходила до нас, и ронять её не за что.
    """
    log = logging.getLogger('asr')
    user = (f'О записи: {about}\n'
            f'Правильные написания — термины: {", ".join(terms)}\n'
            f'Правильные написания — фамилии и имена: {", ".join(names) or "—"}\n'
            f'ЧЕРНОВИК РАСШИФРОВКИ:\n{batch}')
    try:
        res = await llm.complete_json(
            [{'role': 'system', 'content': _SEED_SYS}, {'role': 'user', 'content': user}],
            schema=_SCHEMA, schema_name='glossary_seed', max_tokens=_MAX_TOKENS)
    except Exception as e:
        log.warning('hints: батч %s пропущен — %s: %s', tag, type(e).__name__, str(e)[:120])
        return []
    return _validate((res or {}).get('found') or [], batch, allowed, log)


async def build_hints(full_text: str, llm, *, terms=(), names=(), about: str = '') -> list[dict]:
    """[{heard, canonicals:[term]}] — известные написания, найденные в черновике искажёнными.

    Форма ответа совпадает с элементом глоссария намеренно: дальше по конвейеру ничего менять не
    надо — отбор по вхождению в кусок, подсказка пасса-2 и защита финал-раунда работают как есть.
    """
    terms, names = [str(t).strip() for t in terms if str(t).strip()], \
                   [str(n).strip() for n in names if str(n).strip()]
    if not (terms or names) or not full_text.strip():
        return []
    allowed = {_norm(t): t for t in terms + names if _norm(t)}
    batches = list(_sentence_batches(full_text))
    results = await asyncio.gather(*(
        _one_batch(llm, b, terms, names, about, allowed, f'{i}/{len(batches)}')
        for i, b in enumerate(batches, 1)))

    seen, out = {}, []
    for item in (x for batch in results for x in batch):
        key = item['heard'].lower()
        if key in seen:
            # То же место, другой каноник — обе формы авторские, выберет акустика.
            for c in item['canonicals']:
                if c not in seen[key]['canonicals']:
                    seen[key]['canonicals'].append(c)
            continue
        seen[key] = item
        out.append(item)
    return out


def merge(hints: list[dict], gloss: list[dict]) -> list[dict]:
    """Seed ПЕРВЫМ, затем свободный глоссарий; дедуп по `heard`, seed побеждает.

    Порядок — это приоритет: `relevant()` отдаёт каноники в порядке списка, а бюджет подсказки
    (200 whisper-токенов) кончается раньше, чем каноники. Подтверждённое снаружи знание должно
    попасть в подсказку прежде догадки, построенной по тому же кривому черновику.
    ⓘ Пустой `hints` → список байт в байт прежний.
    """
    out = list(hints)
    seen = {h['heard'].lower() for h in hints}
    for g in gloss:
        if g['heard'].lower() not in seen:
            out.append(g)
    return out


def hinted(hints: list[dict]) -> frozenset[str]:
    """Каноники, подтверждённые seed-проходом, — им можно в подсказку пасса-2 мимо фильтра латиницы.

    ⚠️ Освобождение получает не весь список снаружи, а только то, что прошло ЧЕТЫРЕ звена: снаружи
    предложили → LLM подтвердила искажение в черновике → отбор по вхождению локализовал его в этот
    кусок → гейт редкости пропустил.
    """
    return frozenset(c.casefold() for h in hints for c in h['canonicals'])
