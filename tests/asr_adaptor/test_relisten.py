"""Переслушивание: что считаем подозрительным и что делаем с услышанным.

Стадия меняет текст расшифровки, поэтому тест закрепляет ОБЕ стороны: что она трогает и, главное,
чего НЕ трогает. Датчик, срабатывающий на живой речи, испортит больше, чем починит.

Пороги взяты не с потолка: у каждой формы в распределении живого корпуса есть разрыв между речью
и петлёй (замер 2026-09: 193 записи, 1.44 млн слов), и порог стоит в этом разрыве.
"""

from stages import relisten


def seg(text, start, end, **extra):
    return {"text": text, "start": start, "end": end, **extra}


# --- что считаем подозрительным ----------------------------------------------------------------

def test_серия_одной_буквы_это_петля():
    assert relisten.looped("и дальше " + "И" * 12) == "char"
    assert relisten.looped("ааааааа") == "", "семь букв — ещё речь, порог стоит на восьми"


def test_ряд_знаков_ловится_многоточие_нет():
    assert relisten.looped("ура!!!!!!!!") == "punct"
    assert relisten.looped("и тут... вот так") == ""


def test_повтор_подстроки_внутри_слова():
    assert relisten.looped("сказал СловоСловоСлово потом") == "token"


def test_слово_восемь_раз_подряд():
    assert relisten.looped("нет " * 9) == "word"
    assert relisten.looped("да, да, да, понял") == "", "живой повтор речи не трогаем"


def test_растянутый_сегмент_это_потерянная_речь():
    """Пять секунд звука на одно слово — там не речь, а дыра: выравниватель растянет соседа."""
    assert relisten.stretched([seg("Здравствуйте.", 10.0, 22.0)]) == "stretch"
    assert relisten.stretched([seg("Здравствуйте, коллеги, начнём.", 10.0, 22.0)]) == ""
    assert relisten.stretched([seg("Да.", 10.0, 12.0)]) == ""


def test_кусок_где_почти_нет_слов():
    """⚠️ Петля не всегда выглядит петлёй: в живом прогоне место вышло как «И Слово И Слово» на
    тридцати секундах — ни серии символов, ни повтора, а речи нет. Ловим по плотности: живая речь
    это 2 слова в секунду (медиана корпуса), порча — меньше 0.1."""
    assert relisten.sparse({"raw": "И Слово И Слово", "start": 100.0, "end": 130.0}) == "sparse"
    assert relisten.sparse({"raw": "нормальная речь идёт своим чередом и слов тут хватает",
                            "start": 100.0, "end": 110.0}) == ""
    assert relisten.sparse({"raw": "ага", "start": 100.0, "end": 104.0}) == "", "короткий кусок не трогаем"


def test_подозрение_у_куска_складывается_из_обеих_проверок():
    assert relisten.suspect({"raw": "И" * 10, "segments": []}) == "char"
    assert relisten.suspect({"raw": "Ну.", "segments": [seg("Ну.", 0.0, 9.0)]}) == "stretch"
    assert relisten.suspect({"raw": "обычная речь тут", "segments": [seg("обычная речь тут", 0, 3)]}) == ""


# --- что делаем с услышанным --------------------------------------------------------------------

def test_услышали_речь_берём_речь():
    assert relisten.verdict("И" * 12, "Нам нужно обсудить это отдельно.") == "речь"


def test_услышали_пустоту_значит_тишина():
    """⚠️ Честная дыра лучше сочинённого текста: если речи нет, сочинять нечего."""
    assert relisten.verdict("И" * 12, "") == "тишина"


def test_петлю_меняем_даже_на_одно_слово():
    """Замерено живьём: там, где в записи «ИИИИИИИИИИИИИ», в звуке одно «и». Одно верное слово
    честнее тринадцати выдуманных."""
    assert relisten.verdict("И" * 12, "и") == "коротко"
    c = {"raw": "И" * 12, "segments": []}
    relisten.apply(c, "и", [{"text": "и", "start": 0.2, "end": 0.6}], offset=10.0, decision="коротко")
    assert c["raw"] == "и" and c["relistened"] is True


def test_петля_осталась_значит_не_трогаем():
    assert relisten.verdict("И" * 12, "А" * 20) == "петля осталась"


def test_замена_кладёт_абсолютные_времена():
    c = {"raw": "И" * 12, "segments": [seg("И" * 12, 100.0, 112.0)], "start": 100.0, "end": 112.0}
    relisten.apply(c, "Нам нужно обсудить это отдельно.",
                   [seg("Нам нужно обсудить это отдельно.", 0.5, 9.0)], offset=98.5, decision="речь")
    assert c["raw"].startswith("Нам нужно")
    assert c["segments"][0]["start"] == 99.0 and c["segments"][0]["end"] == 107.5
    assert c["relistened"] is True


def test_тишина_оставляет_честную_дыру_а_не_текст():
    c = {"raw": "И" * 12, "segments": [seg("И" * 12, 10.0, 22.0)]}
    relisten.apply(c, "", [], offset=8.5, decision="тишина")
    assert c["raw"] == "" and c["segments"] == []


def test_петля_осталась_кусок_не_меняется():
    c = {"raw": "И" * 12, "segments": [seg("И" * 12, 10.0, 22.0)]}
    relisten.apply(c, "А" * 20, [seg("А" * 20, 0, 12)], offset=8.5, decision="петля осталась")
    assert c["raw"] == "И" * 12, "не смогли починить — оставили как было, а не заменили мусором"
    assert "relistened" not in c


# --- граница наружу -----------------------------------------------------------------------------

def test_журнал_переслушивания_доезжает_до_артефакта():
    """⚠️⚠️ `x_enriched` собирается по ЯВНОМУ списку полей, и новое поле там теряется молча — так
    уже было с отпечатком установки. Проверяем ту границу, которая уходит наружу.
    """
    from app import _enriched
    base = {"text": "", "turns": [], "markdown": "", "raw_sidecar": {}, "timing": {},
            "speaker_map": {}}
    log = [{"start": 10.0, "end": 22.0, "kind": "char", "verdict": "речь",
            "was": "И" * 12, "now": "Нам нужно обсудить это отдельно."}]
    assert _enriched({**base, "relisten": log})["x_enriched"]["relisten"] == log
    assert "relisten" not in _enriched(base)["x_enriched"], "пусто — ключа нет вовсе"

